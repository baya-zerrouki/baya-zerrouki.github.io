const mobilityTabs = [...document.querySelectorAll('[role="tab"][aria-controls]')];

function selectMobilityTab(selectedTab, moveFocus = false) {
  mobilityTabs.forEach((tab) => {
    const isSelected = tab === selectedTab;
    tab.setAttribute("aria-selected", String(isSelected));
    tab.tabIndex = isSelected ? 0 : -1;
    document.getElementById(tab.getAttribute("aria-controls")).hidden = !isSelected;
  });

  if (moveFocus) selectedTab.focus();
}

mobilityTabs.forEach((tab, index) => {
  tab.addEventListener("click", () => selectMobilityTab(tab));
  tab.addEventListener("keydown", (event) => {
    let nextIndex;

    if (event.key === "ArrowRight") nextIndex = (index + 1) % mobilityTabs.length;
    else if (event.key === "ArrowLeft") nextIndex = (index - 1 + mobilityTabs.length) % mobilityTabs.length;
    else if (event.key === "Home") nextIndex = 0;
    else if (event.key === "End") nextIndex = mobilityTabs.length - 1;
    else return;

    event.preventDefault();
    selectMobilityTab(mobilityTabs[nextIndex], true);
  });
});


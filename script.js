let currentLanguage = "fr";
const languageToggle = document.querySelector(".language-toggle");
const frenchTextNodes = [];
const textWalker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);

while (textWalker.nextNode()) {
  const node = textWalker.currentNode;
  if (node.nodeValue.trim()) {
    frenchTextNodes.push({ node, original: node.nodeValue });
  }
}

const translatedAttributes = [
  { element: document.querySelector(".nav"), attribute: "aria-label", french: "Navigation principale", english: "Primary navigation" },
  { element: document.getElementById("pitch-code"), attribute: "placeholder", french: "Code d'accès", english: "Access code" },
  { element: document.getElementById("pitch-frame"), attribute: "title", french: "Elevator pitch de Baya Zerrouki", english: "Baya Zerrouki's elevator pitch" },
  { element: document.querySelector(".project-photo img[alt*='stabilisateur']"), attribute: "alt", french: "Prototype du stabilisateur vidéo mécanique à deux axes", english: "Prototype of the two-axis mechanical video stabilizer" },
  { element: document.querySelector(".project-photo img[alt*='Snake']"), attribute: "alt", french: "Capture du jeu Snake développé dans le terminal", english: "Screenshot of the Snake game developed in the terminal" }
];

function setLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language;

  frenchTextNodes.forEach(({ node, original }) => {
    const trimmed = original.trim();
    const translated = language === "en" ? translations[trimmed] || trimmed : trimmed;
    const leadingWhitespace = original.match(/^\s*/)[0];
    const trailingWhitespace = original.match(/\s*$/)[0];
    node.nodeValue = `${leadingWhitespace}${translated}${trailingWhitespace}`;
  });

  translatedAttributes.forEach(({ element, attribute, french, english }) => {
    if (element) element.setAttribute(attribute, language === "en" ? english : french);
  });

  document.title = language === "en" ? "Baya Zerrouki – Portfolio" : "Baya Zerrouki – E-portfolio";
  document.querySelector('meta[name="description"]').content = language === "en"
    ? "Baya Zerrouki's portfolio, engineering student at ENSEEIHT (Electrical Engineering, Electronics and Automation)."
    : "E-portfolio de Baya Zerrouki, élève en école d'ingénieurs à l'ENSEEIHT (Énergie électrique, électronique et automatique).";
  languageToggle.textContent = language === "en" ? "FR" : "EN";
  languageToggle.setAttribute("aria-label", language === "en" ? "Afficher le site en français" : "Show the website in English");
  languageToggle.setAttribute("aria-pressed", String(language === "en"));
}

languageToggle.addEventListener("click", () => {
  setLanguage(currentLanguage === "fr" ? "en" : "fr");
});

/* =========================================================
   Elevator pitch : la vidéo s'affiche seulement si le bon code est saisi.

   ⚠ Important : ce site est "statique" (aucun serveur). La vérification se
   fait donc dans le navigateur de la personne. Elle écarte les curieux, mais
   ne constitue pas une sécurité absolue : quelqu'un qui lit le code source de
   la page pourrait retrouver le lien de la vidéo. Pour qu'elle reste discrète,
   publie-la sur YouTube en mode « Non répertoriée » (jamais « Publique »).
   ========================================================= */

/* 1) LE LIEN DE TA VIDÉO
   YouTube : "https://www.youtube.com/embed/IDENTIFIANT_DE_LA_VIDEO"
   (l'identifiant est la suite de lettres après "v=" dans l'adresse de la vidéo) */
const VIDEO_URL = "https://www.youtube.com/embed/ID_DE_LA_VIDEO";

/* 2) L'EMPREINTE (hash) DE TON CODE
   On ne stocke jamais le code en clair, seulement son empreinte SHA-256.
   Code de démonstration actuel : demo2026
   Pour choisir ton propre code, ouvre Git Bash et tape (remplace monCode) :
       printf 'monCode' | sha256sum
   puis colle ici les 64 caractères obtenus à la place de ceux ci-dessous. */
const CODE_HASH = "43c27b4e263fa191a6a7ec198cd4d5b47d17413c49d77dc533a01720707e3202";

/* ---------------------------------------------------------
   Le reste du fichier n'a pas besoin d'être modifié
   --------------------------------------------------------- */
const formulaire = document.getElementById("pitch-form");
const champCode = document.getElementById("pitch-code");
const message = document.getElementById("pitch-message");
const zoneVideo = document.getElementById("pitch-video");
const cadreVideo = document.getElementById("pitch-frame");

/* Transforme un texte en empreinte SHA-256 (64 caractères hexadécimaux) */
async function empreinte(texte) {
  const octets = new TextEncoder().encode(texte);
  const resultat = await crypto.subtle.digest("SHA-256", octets);
  return Array.from(new Uint8Array(resultat))
    .map((octet) => octet.toString(16).padStart(2, "0"))
    .join("");
}

if (formulaire) {
  formulaire.addEventListener("submit", async (evenement) => {
    evenement.preventDefault();              // empêche le rechargement de la page

    const saisie = champCode.value.trim();   // le code tapé, sans espaces autour
    const hashSaisie = await empreinte(saisie);

    if (hashSaisie !== CODE_HASH) {
      message.textContent = currentLanguage === "en"
        ? "Incorrect code. Check it and try again."
        : "Code incorrect. Vérifie-le et réessaie.";
      message.className = "pitch-message erreur";
      return;
    }

    if (VIDEO_URL.includes("ID_DE_LA_VIDEO")) {
      message.textContent = currentLanguage === "en"
        ? "Correct code, but the video has not been added yet."
        : "Code correct, mais la vidéo n'a pas encore été ajoutée.";
      message.className = "pitch-message ok";
      return;
    }

    cadreVideo.src = VIDEO_URL;              // on charge la vidéo seulement maintenant
    zoneVideo.hidden = false;                // on affiche le lecteur
    message.textContent = currentLanguage === "en"
      ? "Correct code. Enjoy watching!"
      : "Code correct, bon visionnage !";
    message.className = "pitch-message ok";
  });
}